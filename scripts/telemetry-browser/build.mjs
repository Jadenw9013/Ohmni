// Reproducibly bundle entry.mjs into apps/web/vendor/sentry-telemetry.js.
//
//   npm ci --prefix scripts/telemetry-browser
//   node scripts/telemetry-browser/build.mjs          # write bundle + metadata
//   node scripts/telemetry-browser/build.mjs --check  # fail if committed files drift
//
// The bundle is committed (like vendored Three.js) so Vercel's no-build static
// publication and the demo server's fixed asset snapshot serve it unchanged.
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { build, version as esbuildVersion } from "esbuild";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..", "..");
const vendor = join(root, "apps", "web", "vendor");
const pinned = JSON.parse(readFileSync(join(here, "package.json"), "utf8")).dependencies;
const sdkPackage = JSON.parse(readFileSync(join(here, "node_modules", "@sentry", "browser", "package.json"), "utf8"));
if (sdkPackage.version !== pinned["@sentry/browser"] || esbuildVersion !== pinned.esbuild) {
    throw new Error("installed bundle toolchain does not match the pinned versions; run npm ci");
}

const result = await build({
    absWorkingDir: here,
    entryPoints: ["entry.mjs"],
    bundle: true,
    format: "esm",
    platform: "browser",
    target: ["es2020"],
    minify: true,
    legalComments: "none",
    charset: "ascii",
    sourcemap: false,
    write: false,
    logLevel: "silent",
});
const header = `/* Ohmni telemetry adapter: @sentry/browser ${sdkPackage.version} (MIT, see SENTRY-LICENSE.txt), esbuild ${esbuildVersion}. Generated by scripts/telemetry-browser/build.mjs; do not edit. */\n`;
const bundle = Buffer.from(header + result.outputFiles[0].text, "utf8");
const license = readFileSync(join(here, "node_modules", "@sentry", "browser", "LICENSE"));
const metadata = Buffer.from(JSON.stringify({
    bundle: "sentry-telemetry.js",
    sdk: "@sentry/browser",
    sdk_version: sdkPackage.version,
    license: "MIT",
    license_file: "SENTRY-LICENSE.txt",
    bundler: "esbuild",
    bundler_version: esbuildVersion,
    source: "scripts/telemetry-browser/entry.mjs",
    bytes: bundle.length,
    sha256: createHash("sha256").update(bundle).digest("hex"),
}, null, 2) + "\n", "utf8");

for (const text of [bundle.toString("utf8")]) {
    // Never publish an absolute build path from this machine.
    if (text.includes(root) || /\/(home|tmp|Users)\//.test(text)) throw new Error("bundle embeds a local path");
}

const outputs = [
    [join(vendor, "sentry-telemetry.js"), bundle],
    [join(vendor, "sentry-telemetry.json"), metadata],
    [join(vendor, "SENTRY-LICENSE.txt"), license],
];
if (process.argv.includes("--check")) {
    const stale = outputs.filter(([path, data]) => {
        try { return !readFileSync(path).equals(data); } catch { return true; }
    }).map(([path]) => relative(root, path));
    if (stale.length) {
        console.error(`telemetry bundle is not reproducible from source: ${stale.join(", ")}`);
        process.exit(1);
    }
    console.log("telemetry bundle reproduced byte-for-byte");
} else {
    for (const [path, data] of outputs) writeFileSync(path, data);
    console.log(`wrote ${relative(root, outputs[0][0])} (${bundle.length} bytes)`);
}
